#!/usr/bin/env python
"""Call the whole modelled call space of utils/python_names.h natively, found by GCC 16 reflection,
and check it against the model and Python's own answers.

What it does, in order (artifacts under build/callspace/python_names/run-<ns>/):

1. writes callspace_domains.h from the model (tests/unittests/python_names_callspace.py);
2. builds python_names_probe.cpp with GCC 16 (-std=c++26 -freflection, gcov instrumentation) — the
   probe reflects every function of pygim::python_names and refuses to compile one it has no model
   for — runs it, and reads the cases it called;
3. checks them: the functions, parameters and result kinds reflection found against the model's
   declaration (schema drift); each function's calls against the product rebuilt from the model
   (missing, unexpected, duplicate, shrunken domain); each native result against the oracle;
4. records gcov's line, branch and condition coverage of every function in python_names.h;
5. negative controls, each of which must be caught: a deleted case with its count adjusted; the
   probe rebuilt on a self-consistently shrunken domain; mutated copies of python_names.h, each a
   behavioural defect, run natively AND compiled against the every-build proof
   (tests/static/python_names_callspace_proofs.cpp); a function added to the namespace, which must
   fail to compile.

Run with the dnd interpreter: python tests/static/run_python_names_callspace.py [--compiler g++-16]
Needs GCC 16 with -freflection; nothing here is part of the extension build or the pytest suite.
"""

from __future__ import annotations

import argparse
import copy
import gzip
import json
import os
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tests" / "unittests"))

import callspace  # noqa: E402
import python_names_callspace as model  # noqa: E402

HEADER = ROOT / "src" / "_pygim_fast" / "utils" / "python_names.h"

# Behavioural defects: (name, the text replaced in python_names.h, its replacement). Each is a plausible
# wrong rule; the first is the rule pygim had before it matched enum._is_dunder.
MUTANTS = (
    ("is_dunder ignores longer underscore runs",
     " && name[2] != '_' &&\n           name[name.size() - 3] != '_';", ";"),
    ("owner_of keeps the leading underscores",
     "std::string_view{} : class_name.substr(first);", "std::string_view{} : class_name;"),
    ("is_private_name forgets the dotted name",
     " && name.find('.') == std::string_view::npos;", ";"),
    ("unmangled accepts any rest",
     "return is_private_name(rest) ? rest : std::string_view{};", "return rest;"),
    ("requalified forgets the dot after the owner",
     " || qualname[from.size()] != '.')", ")"),
)
ADDED_FUNCTION = ("\n/// A rule nobody modelled yet.\nconstexpr bool is_internal(std::string_view label) noexcept {\n"
                  "    return label.starts_with(\"_\");\n}\n\n}  // namespace pygim::python_names")


def run(argv, cwd, timeout=300):
    started = time.perf_counter()
    result = subprocess.run([str(a) for a in argv], cwd=str(cwd), capture_output=True, text=True, timeout=timeout)
    return result, time.perf_counter() - started


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def domains_header(drop=None):
    """callspace_domains.h: the model's role domains, optionally with one (role, value) left out."""
    arrays = {"class_names": model.CLASS_NAMES, "names": model.NAMES, "qualnames": model.QUALNAMES}
    lines = ["// GENERATED by tests/static/run_python_names_callspace.py from the model — do not edit.",
             "#pragma once", "#include <array>", "#include <string_view>", '#include "named_call_space.h"',
             "namespace callspace_domains {"]
    for array, domain in arrays.items():
        values = [v for v in domain.expand() if drop != (array, v)]
        lines.append(f"inline constexpr std::array<std::string_view, {len(values)}> {array}{{"
                     + ", ".join(model._cpp(v) for v in values) + "};")
    by_role = {"class_name": "class_names", "from": "class_names", "to": "class_names", "name": "names",
               "qualname": "qualnames"}
    lines.append("struct domains {")
    lines.append(f"    static constexpr std::array<named_call_space::role_domain, {len(by_role)}> roles{{{{"
                 + ", ".join(f"{{{model._cpp(r)}, {a}}}" for r, a in by_role.items()) + "}};")
    lines.append(f"    static constexpr std::array<std::string_view, {len(model.FUNCTIONS)}> functions{{"
                 + ", ".join(model._cpp(f) for f in model.FUNCTIONS) + "};")
    lines += ["};", "}  // namespace callspace_domains", ""]
    return "\n".join(lines)


def build(out_dir, include_first, compiler, coverage):
    write(out_dir / "callspace_domains.h", domains_header() if include_first is None else include_first[1])
    includes = [out_dir, HERE] + ([include_first[0]] if include_first and include_first[0] else []) + [HEADER.parent]
    argv = [compiler, "-std=c++26", "-freflection", "-O0", "-g", "-Wall", "-Wextra"]
    if coverage:
        argv += ["--coverage", "-fcondition-coverage"]
    argv += [f"-I{p}" for p in includes] + [HERE / "python_names_probe.cpp", "-o", out_dir / "probe"]
    result, seconds = run(argv, out_dir)
    write(out_dir / "build.log", result.stdout + result.stderr)
    return result, seconds, argv


def probe(out_dir):
    result, seconds = run([out_dir / "probe"], out_dir)
    if result.returncode:
        raise RuntimeError(f"probe failed:\n{result.stderr}")
    return json.loads(result.stdout), seconds


def schema_issues(document):
    """What reflection found that the model does not declare, or declares differently."""
    issues = []
    found = {f["name"]: f for f in document["functions"]}
    for name in sorted(set(found) ^ set(model.FUNCTIONS)):
        issues.append({"kind": "function_set_drift", "function": name})
    for name, (parameters, kind) in model.FUNCTIONS.items():
        if name in found:
            reflected = found[name]
            if tuple(p["name"] for p in reflected["parameters"]) != parameters:
                issues.append({"kind": "parameter_drift", "function": name})
            if reflected["result_kind"] != kind:
                issues.append({"kind": "result_drift", "function": name})
    return issues


def runs(document):
    """{function: callspace.Run}: the native cases, each judged against the oracle."""
    result = {}
    for function in document["functions"]:
        name = function["name"]
        m = model.MODELS[name]
        records = []
        for case in function["cases"]:
            want, oracle = model.expected(name, case["arguments"])
            records.append({"id": callspace.case_id(m, case["arguments"]), "arguments": case["arguments"],
                            "expected": want, "oracle": oracle, "outcome": case["native_result"],
                            "passed": case["native_result"] == want})
        result[name] = callspace.Run(model=m.name, advertised={p["name"]: p["domain"] for p in function["parameters"]},
                                     records=records, count=function["case_count"])
    return result


def coverage(out_dir, gcov):
    notes = sorted(out_dir.glob("*.gcno"))
    result, _ = run([gcov, "--json-format", "--branch-probabilities", "--branch-counts", "--conditions",
                     *notes], out_dir)
    write(out_dir / "gcov.log", result.stdout + result.stderr)
    per_function = {}
    for archive in out_dir.glob("*.gcov.json.gz"):
        for entry in json.loads(gzip.decompress(archive.read_bytes()))["files"]:
            if not entry["file"].endswith("utils/python_names.h"):
                continue
            for function in entry["functions"]:
                short = function["demangled_name"].split("(")[0].rsplit("::", 1)[-1].split("[abi:")[0]
                lines = [line for line in entry["lines"] if line.get("function_name") == function["name"]]
                branches = [b for line in lines for b in line.get("branches", [])]
                conditions = [c for line in lines for c in line.get("conditions", [])]
                per_function[short] = {
                    "executions": function["execution_count"],
                    "lines": f"{sum(line['count'] > 0 for line in lines)}/{len(lines)}",
                    "branches": f"{sum(b['count'] > 0 for b in branches)}/{len(branches)}",
                    "branches_not_taken": [{"line": line["line_number"], "throw": b.get("throw", False)}
                                           for line in lines for b in line.get("branches", []) if b["count"] == 0],
                    "conditions": f"{sum(c['covered'] for c in conditions)}/{sum(c['count'] for c in conditions)}",
                }
    return per_function


def without_examples(header_text):
    """The header without its own examples — the namespace-scope static_asserts under each function
    (project #252). A mutant must compile for the probe and the every-build proof to be shown catching
    it; whether the examples alone refuse it is reported apart (examples_refuse)."""
    kept, lines, index = [], header_text.splitlines(keepends=True), 0
    while index < len(lines):
        if not lines[index].startswith("static_assert("):
            kept.append(lines[index])
            index += 1
            continue
        depth = 0
        while True:                                   # to the line where the statement's parentheses close
            code, quoted = lines[index].split("//", 1)[0], False
            for at, char in enumerate(code):
                if char == '"' and (at == 0 or code[at - 1] != "\\"):
                    quoted = not quoted
                elif not quoted:
                    depth += (char == "(") - (char == ")")
            index += 1
            if depth <= 0 and code.rstrip().endswith(";"):
                break
    return "".join(kept)


def examples_refuse(mutant_root, header_text, cxx):
    """Whether the header's own examples refuse a mutated header: one translation unit that includes it."""
    write(mutant_root / "python_names.h", header_text)
    write(mutant_root / "examples.cpp", '#include "python_names.h"\nint main() {}\n')
    result, _ = run([cxx, "-std=c++23", "-fsyntax-only", mutant_root / "examples.cpp"], mutant_root)
    return result.returncode != 0


def mutant_proof_fails(mutant_root, header_text, conda_cxx):
    """Compile the every-build proof against a mutated header; the names of the failing functions."""
    write(mutant_root / "src" / "_pygim_fast" / "utils" / "python_names.h", header_text)
    for name in ("python_names_callspace_proofs.cpp", "case_table.h"):
        write(mutant_root / "tests" / "static" / name, (HERE / name).read_text(encoding="utf-8"))
    result, _ = run([conda_cxx, "-std=c++23", "-fsyntax-only", "-fmax-errors=20",
                     mutant_root / "tests" / "static" / "python_names_callspace_proofs.cpp"], mutant_root)
    write(mutant_root / "proof.log", result.stdout + result.stderr)
    failing = sorted({f for f in model.FUNCTIONS if f"first_failing_{f}_call" in result.stderr})
    return result.returncode != 0, failing


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--compiler", default="/usr/bin/g++-16")
    parser.add_argument("--gcov", default="/usr/bin/gcov-16")
    parser.add_argument("--proof-compiler", default=str(Path(sys.executable).parent / "x86_64-conda-linux-gnu-c++"),
                        help="the extension build's compiler, for the every-build proof against the mutants")
    parser.add_argument("--output", default=str(ROOT / "build" / "callspace" / "python_names"))
    args = parser.parse_args(argv)
    out = Path(args.output) / f"run-{time.time_ns()}"
    out.mkdir(parents=True)
    report = {"artifacts": str(out), "header": str(HEADER.relative_to(ROOT)), "controls": {}, "seconds": {}}

    # 1-4: the probe, its cases, the checks, coverage.
    result, report["seconds"]["compile"], argv_used = build(out, None, args.compiler, coverage=True)
    if result.returncode:
        raise SystemExit(f"probe did not compile: see {out / 'build.log'}")
    document, report["seconds"]["probe"] = probe(out)
    write(out / "cases.json", json.dumps(document, ensure_ascii=False))
    report["compiler"] = document["compiler"]
    report["command"] = [str(a) for a in argv_used]
    report["schema_issues"] = schema_issues(document)
    native = runs(document)
    report["functions"] = {name: callspace.summary(model.MODELS[name], run) for name, run in native.items()}
    report["coverage"] = coverage(out, args.gcov)

    # 5a: a case deleted, its count adjusted.
    deleted = copy.deepcopy(native["respelt"])
    gone = deleted.records.pop(len(deleted.records) // 2)
    deleted.count -= 1
    issues = callspace.check(model.MODELS["respelt"], deleted)
    report["controls"]["deleted_case"] = {"deleted": gone["arguments"], "caught_by": [i["kind"] for i in issues]}

    # 5b: the probe rebuilt on a domain that lost one name, its cases consistent with it.
    shrunk_dir = out / "shrunk"
    shrunk_dir.mkdir()
    result, _, _ = build(shrunk_dir, (None, domains_header(drop=("names", "__x"))), args.compiler, coverage=False)
    shrunk_doc, _ = probe(shrunk_dir)
    shrunk = runs(shrunk_doc)
    consistent = all(f["case_count"] == len(f["cases"]) for f in shrunk_doc["functions"])
    caught = {name: sorted({i["kind"] for i in callspace.check(model.MODELS[name], r)}) for name, r in shrunk.items()}
    report["controls"]["shrunken_domain"] = {"dropped": "names: '__x'", "self_consistent": consistent,
                                             "caught_by": caught}

    # 5c: behavioural defects, natively and against the every-build proof.
    header_text = HEADER.read_text(encoding="utf-8")
    report["controls"]["mutants"] = []
    for index, (name, old, new) in enumerate(MUTANTS):
        assert header_text.count(old) == 1, f"mutant {name!r} no longer applies to python_names.h"
        with_examples = header_text.replace(old, new, 1)
        mutated = without_examples(with_examples)
        mutant_dir = out / f"mutant-{index}"
        examples_refused = examples_refuse(mutant_dir / "examples", with_examples, args.proof_compiler)
        write(mutant_dir / "include" / "python_names.h", mutated)
        # The probe's quoted include finds the mutant's directory before the real header's.
        result, _, _ = build(mutant_dir, (mutant_dir / "include", domains_header()), args.compiler, coverage=False)
        if result.returncode:
            raise SystemExit(f"mutant {name!r} did not compile: see {mutant_dir / 'build.log'}")
        mutant_doc, _ = probe(mutant_dir)
        mutant_runs = runs(mutant_doc)
        failures = {f: sum(not r["passed"] for r in run_.records) for f, run_ in mutant_runs.items()}
        refused, failing = mutant_proof_fails(mutant_dir / "proof", mutated, args.proof_compiler)
        report["controls"]["mutants"].append({
            "defect": name, "native_failures": {f: n for f, n in failures.items() if n},
            "space_intact": all(not [i for i in callspace.check(model.MODELS[f], r) if i["kind"] != "oracle_failures"]
                                for f, r in mutant_runs.items()),
            "every_build_proof_refused": refused, "proof_names": failing, "examples_refused": examples_refused})

    # 5d: a function added to the namespace must not compile into the probe.
    drift_dir = out / "drift"
    drifted = header_text.rstrip().removesuffix("}  // namespace pygim::python_names") + ADDED_FUNCTION + "\n"
    write(drift_dir / "include" / "python_names.h", drifted)
    result, _, _ = build(drift_dir, (drift_dir / "include", domains_header()), args.compiler, coverage=False)
    report["controls"]["added_function"] = {
        "refused": result.returncode != 0,
        "message": next((line.strip() for line in result.stderr.splitlines() if "Unmodeled reflected" in line), None)}

    write(out / "report.json", json.dumps(report, indent=2, ensure_ascii=False, default=str))
    write(Path(args.output) / "latest.json", json.dumps({"artifacts": str(out)}))
    print(render(report))
    write(out / "report.txt", render(report))
    ok = (not report["schema_issues"]
          and all(not s["issues"] for s in report["functions"].values())
          and "missing_calls" in report["controls"]["deleted_case"]["caught_by"]
          and report["controls"]["shrunken_domain"]["self_consistent"]
          and all("domain_shrunk" in kinds for name, kinds in report["controls"]["shrunken_domain"]["caught_by"].items()
                  if "name" in model.FUNCTIONS[name][0])
          and all(m["native_failures"] and m["space_intact"] and m["every_build_proof_refused"]
                  for m in report["controls"]["mutants"])
          and report["controls"]["added_function"]["refused"])
    print("RESULT:", "all checks held" if ok else "A CHECK FAILED")
    return 0 if ok else 1


def render(report):
    lines = ["utils/python_names.h: the reflected call space", "",
             f"compiler: {report['compiler']}", f"artifacts: {report['artifacts']}", "",
             f"{'function':<16}{'product':>8}{'required':>9}{'called':>8}{'passed':>8}  oracles"]
    for name, s in report["functions"].items():
        lines.append(f"{name:<16}{s['product']:>8}{s['required']:>9}{s['executed']:>8}{s['passed']:>8}  "
                     + ", ".join(f"{k} {v}" for k, v in s["oracles"].items())
                     + ("" if not s["issues"] else f"  ISSUES {s['issues']}"))
    total = sum(s["executed"] for s in report["functions"].values())
    lines += [f"{'total':<16}{'':>8}{'':>9}{total:>8}", "",
              f"schema drift: {report['schema_issues'] or 'none'}", "", "gcov, per function:"]
    for name, c in sorted(report["coverage"].items()):
        lines.append(f"  {name:<16} runs {c['executions']:>6}  lines {c['lines']:>6}  branches {c['branches']:>6}"
                     f"  conditions {c['conditions']:>6}")
    controls = report["controls"]
    lines += ["", "negative controls:",
              f"  deleted case ({controls['deleted_case']['deleted']}): caught by {controls['deleted_case']['caught_by']}",
              f"  shrunken domain ({controls['shrunken_domain']['dropped']}, self-consistent: "
              f"{controls['shrunken_domain']['self_consistent']}):"]
    lines += [f"    {name}: {kinds}" for name, kinds in controls["shrunken_domain"]["caught_by"].items()]
    for m in controls["mutants"]:
        lines.append(f"  defect '{m['defect']}': native failures {m['native_failures']}; space intact {m['space_intact']};"
                     f" every-build proof refused {m['every_build_proof_refused']} at {m['proof_names']};"
                     f" the header's own examples refused it {m['examples_refused']}")
    lines.append(f"  added function: refused {controls['added_function']['refused']}: "
                 f"{controls['added_function']['message']}")
    lines.append("")
    lines.append("seconds: " + ", ".join(f"{k} {v:.2f}" for k, v in report["seconds"].items()))
    return "\n".join(lines)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
