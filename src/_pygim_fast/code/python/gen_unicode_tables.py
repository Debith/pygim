#!/usr/bin/env python3.14
"""Generate unicode_tables.gen.h — which characters beyond ASCII may start or continue a Python
identifier (XID_Start and XID_Continue, as the running Python's str.isidentifier() reads them).

The lexer refuses a name holding any other character, as CPython's tokenizer does ("invalid
character '€' (U+20AC)"). The Unicode version is the running Python's:

    python3.14 src/_pygim_fast/code/python/gen_unicode_tables.py

tests/unittests/test_code_parse.py asserts the committed header is what python3.14 generates.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "unicode_tables.gen.h"


def ranges(pred):
    """The runs of code points from U+0080 for which pred holds, as (first, last) pairs."""
    out, start = [], None
    for c in range(0x80, 0x110000):
        ok = pred(c)
        if ok and start is None:
            start = c
        elif not ok and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, pairs):
    lines = [f"inline constexpr std::array<std::uint32_t, {2 * len(pairs)}> {name}{{"]
    flat = [f"0x{v:X}" for pair in pairs for v in pair]
    for i in range(0, len(flat), 12):
        lines.append("    " + ", ".join(flat[i:i + 12]) + ",")
    lines.append("};")
    return lines


def render():
    start = ranges(lambda c: chr(c).isidentifier())
    cont = ranges(lambda c: ("a" + chr(c)).isidentifier())
    lines = [
        "#pragma once",
        "// GENERATED by src/_pygim_fast/code/python/gen_unicode_tables.py from Python "
        f"{sys.version_info.major}.{sys.version_info.minor} (Unicode {unicodedata.unidata_version}) — do not edit.",
        "//",
        "// The code points beyond ASCII that may start (XID_Start) or continue (XID_Continue) a Python",
        "// identifier, as sorted (first, last) pairs: a binary search finds whether one holds.",
        "//",
        "// CORE layer: pybind-free.",
        "",
        "#include <algorithm>",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <ranges>",
        "",
        "namespace pygim::code::python::unicode {",
        "",
        *table("identifier_start", start),
        "",
        *table("identifier_continue", cont),
        "",
        "namespace detail {",
        "// Whether cp is in one of the ranges [first, last] that `pairs` holds as first, last, first, ...:",
        "// the first range whose last is not before cp holds it when its first is not past it.",
        "template <std::size_t N>",
        "[[nodiscard]] constexpr bool in(const std::array<std::uint32_t, N>& pairs, std::uint32_t cp) noexcept {",
        "    const auto ranges = std::views::iota(std::size_t{0}, N / 2);",
        "    const auto it = std::ranges::partition_point(ranges, [&](std::size_t r) { return pairs[2 * r + 1] < cp; });",
        "    return it != ranges.end() && pairs[2 * *it] <= cp;",
        "}",
        "static_assert(in(std::array<std::uint32_t, 4>{1, 3, 7, 9}, 8) && in(std::array<std::uint32_t, 4>{1, 3, 7, 9}, 1) &&",
        "              !in(std::array<std::uint32_t, 4>{1, 3, 7, 9}, 5) && !in(std::array<std::uint32_t, 4>{1, 3, 7, 9}, 10));",
        "}  // namespace detail",
        "",
        "/// Whether a code point beyond ASCII may start an identifier.",
        "[[nodiscard]] constexpr bool starts_identifier(std::uint32_t cp) noexcept { return detail::in(identifier_start, cp); }",
        "/// Whether a code point beyond ASCII may continue an identifier.",
        "[[nodiscard]] constexpr bool continues_identifier(std::uint32_t cp) noexcept { return detail::in(identifier_continue, cp); }",
        "",
        "static_assert(starts_identifier(0xE4) && !starts_identifier(0x20AC) && continues_identifier(0x0301) && !starts_identifier(0x0301));",
        "",
        "}  // namespace pygim::code::python::unicode",
        "",
    ]
    return "\n".join(lines)


def main():
    text = render()
    if len(sys.argv) > 1 and sys.argv[1] == "--print":
        sys.stdout.write(text)
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
