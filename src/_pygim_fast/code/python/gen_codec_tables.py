#!/usr/bin/env python3.14
"""Generate codec_tables.gen.h — every codec a coding cookie may name (PEP 263), as the running
Python's codec registry knows them: each codec's form (how source.h turns its bytes into UTF-8),
a single-byte codec's characters for the bytes 0x80-0xFF, and every name the registry takes.

Forms: utf-8 and ascii are checked as they are; a table codec (cp1252, koi8-r, iso8859-*, mac-*,
...: ASCII-compatible, decoding by a table, 62 in Python 3.14) and latin-1 (its table is its
bytes) go through their table; a codec that is no text encoding (base64, rot13) is refused as
CPython refuses it; every other one (shift_jis, gbk, utf-16) is known and not read here. A name
the registry does not know is an unknown encoding.

    python3.14 src/_pygim_fast/code/python/gen_codec_tables.py

tests/unittests/test_code_parse.py asserts the committed header is what python3.14 generates. The
header names the release that made it: a patch release can add names (3.14.6 added eight of IANA's,
CPython gh-149801), so it is made by the newest 3.14, and a python3.14 older than that skips the test.
"""

from __future__ import annotations

import importlib
import pkgutil
import sys
from pathlib import Path

import encodings
from encodings.aliases import aliases

HERE = Path(__file__).resolve().parent
OUT = HERE / "codec_tables.gen.h"
UNDEFINED = 0xFFFE   # what Python's decoding tables hold for a byte the codec does not define


def codecs():
    """(module name, form, the 128 characters of 0x80-0xFF or None) for every codec module the
    registry can import here (mbcs and oem are Windows'), in name order."""
    out = []
    for m in sorted(pkgutil.iter_modules(encodings.__path__), key=lambda m: m.name):
        try:
            mod = importlib.import_module("encodings." + m.name)
        except ImportError:
            continue
        if not hasattr(mod, "getregentry"):
            continue   # the package's own helpers: aliases, _win_cp_codecs
        table = getattr(mod, "decoding_table", None)
        if not mod.getregentry()._is_text_encoding:
            out.append((m.name, "not_text", None))
        elif m.name in ("utf_8", "ascii"):
            out.append((m.name, "utf8" if m.name == "utf_8" else "ascii", None))
        elif m.name == "latin_1":
            out.append((m.name, "table", list(range(0x80, 0x100))))
        elif isinstance(table, str) and len(table) == 256 and table[:128] == "".join(map(chr, range(128))):
            out.append((m.name, "table", [ord(c) for c in table[128:]]))
        else:
            out.append((m.name, "unsupported", None))
    return out


def render():
    found = codecs()
    tables = [name for name, form, _ in found if form == "table"]
    table_of = {name: i for i, name in enumerate(tables)}
    form_of = {name: form for name, form, _ in found}
    # A name the registry takes: an alias (it wins where a module has the same name, as
    # search_function looks aliases up first), or a codec module's own name.
    names = {name: (name, False) for name in form_of}
    names.update({a: (t, True) for a, t in aliases.items() if t in form_of})

    def codec(target):
        form = form_of[target]
        return f"codec(form::table, {table_of[target]})" if form == "table" else f"codec(form::{form})"

    lines = [
        "#pragma once",
        "// GENERATED by src/_pygim_fast/code/python/gen_codec_tables.py from Python "
        f"{'.'.join(map(str, sys.version_info[:3]))}'s codecs — do not edit.",   # a patch release adds names (3.14.6: IANA's)
        "//",
        "// Every codec a coding cookie may name: its form, a single-byte codec's characters for the",
        "// bytes 0x80-0xFF (0xFFFE: the codec defines none), and every name the codec registry takes",
        "// for it, sorted, in the registry's spelling (lower case, runs of other characters than",
        "// letters, digits and '.' as one '_').",
        "//",
        "// CORE layer: pybind-free.",
        "",
        "#include <algorithm>",
        "#include <array>",
        "#include <cstdint>",
        "#include <optional>",
        "#include <string_view>",
        "",
        "namespace pygim::code::python::codecs {",
        "",
        f"inline constexpr std::uint16_t undefined = 0x{UNDEFINED:X};",
        "",
        "/// Each table codec's characters for 0x80-0xFF (latin_1's are its bytes).",
        f"inline constexpr std::array<std::array<std::uint16_t, 128>, {len(tables)}> upper_half{{{{",
    ]
    for name, form, chars in found:
        if form != "table":
            continue
        lines.append(f"    {{{{ // {name}")
        for i in range(0, 128, 16):
            lines.append("        " + ", ".join(f"0x{c:04X}" for c in chars[i:i + 16]) + ",")
        lines.append("    }},")
    lines.append("}};")
    lines += [
        "",
        "/// How a codec's bytes become UTF-8: checked as UTF-8 or as ASCII, through a table of the",
        "/// upper half, or not here: no text encoding (base64), or one not read yet (shift_jis).",
        "enum class form : std::uint8_t { utf8, ascii, table, not_text, unsupported };",
        "",
        "/// A codec the registry knows: its form and, for a table codec, its index in upper_half.",
        "class codec {",
        "public:",
        "    constexpr codec(enum form f, std::uint8_t table = 0) noexcept : m_form(f), m_table(table) {}",
        "    [[nodiscard]] constexpr enum form form() const noexcept { return m_form; }",
        "    [[nodiscard]] constexpr std::uint8_t table() const noexcept { return m_table; }",
        "",
        "private:",
        "    enum form m_form;",
        "    std::uint8_t m_table;",
        "};",
        "",
        "/// A name the registry takes for a codec: an alias (encodings.aliases) or its module's own.",
        "class codec_name {",
        "public:",
        "    constexpr codec_name(std::string_view name, bool alias, codec c) noexcept : m_name(name), m_alias(alias), m_codec(c) {}",
        "    [[nodiscard]] constexpr std::string_view name() const noexcept { return m_name; }",
        "    [[nodiscard]] constexpr bool alias() const noexcept { return m_alias; }",
        "    [[nodiscard]] constexpr codec get() const noexcept { return m_codec; }",
        "",
        "private:",
        "    std::string_view m_name;",
        "    bool m_alias;",
        "    codec m_codec;",
        "};",
        f"inline constexpr std::array<codec_name, {len(names)}> names{{{{",
    ]
    for name, (target, alias) in sorted(names.items()):
        lines.append(f'    codec_name("{name}", {"true" if alias else "false"}, {codec(target)}),')
    lines.append("}};")
    cp1252 = table_of["cp1252"]
    lines += [
        "",
        "/// The entry for a name in the registry's spelling, if the registry takes it.",
        "[[nodiscard]] constexpr std::optional<codec_name> name_of(std::string_view key) noexcept {",
        "    const auto it = std::ranges::lower_bound(names, key, {}, &codec_name::name);",
        "    return it != names.end() && it->name() == key ? std::optional<codec_name>(*it) : std::nullopt;",
        "}",
        f'static_assert(name_of("windows_1252")->get().table() == {cp1252} && name_of("utf8")->get().form() == form::utf8 &&',
        '              name_of("latin1")->get().form() == form::table && name_of("base64")->get().form() == form::not_text &&',
        '              name_of("shift_jis")->get().form() == form::unsupported && !name_of("no_such_codec") &&',
        f"              upper_half[{cp1252}][0x80 - 0x80] == 0x20AC);   // cp1252's 0x80 is the euro sign",
        "",
        "}  // namespace pygim::code::python::codecs",
        "",
    ]
    return "\n".join(lines)


def main():
    text = render()
    if len(sys.argv) > 1 and sys.argv[1] == "--print":
        sys.stdout.write(text)
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
